public class PopulationData {
    public static void main(String[] args) {
        // Storing populations using long primitive types
        // Approximate estimates as of recent demographic data
        long indiaPopulation = 1_430_000_000L;
        long chinaPopulation = 1_410_000_000L;

        // Printing the stored population values
        System.out.println("Country Population Overview:");
        System.out.println("---------------------------");
        System.out.println("India Population: " + indiaPopulation);
        System.out.println("China Population: " + chinaPopulation);
    }
}
